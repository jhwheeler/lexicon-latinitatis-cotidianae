#!/usr/bin/env python3
"""Build the lexicon site from its data and templates (stdlib only).

Inputs: data/catalog.json, data/entries/<category>.json (grouped entries),
data/concepts/<concept>.json (one record per concept), data/rulings.json
(editorial rulings) and the templates in src/.

Outputs: index.html (the searchable single page), c/<concept>.html (one page
per concept record), how-we-decide.html (editorial policy), rulings.html (the
rulings register), sitemap.xml and assets/lexicon.css. See docs/data-format.md
and docs/records.md.
"""
import argparse
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path, PurePosixPath
import posixpath
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
SITE_URL = 'https://jhwheeler.github.io/lexicon-latinitatis-cotidianae/'
SITE_NAME = 'Lexicon Latīnitātis Cotīdiānae'
GENERATED = '<!-- Generated by scripts/build.py. Edit data/ and src/, then rebuild. -->\n'
ENTRY_ID = r'entry-[1-9][0-9]*'
SLUG = r'[a-z0-9]+(?:-[a-z0-9]+)*'
DATE = r'20[0-9]{2}-(?:0[1-9]|1[0-2])(?:-(?:0[1-9]|[12][0-9]|3[01]))?'
MONTHS = ('January', 'February', 'March', 'April', 'May', 'June', 'July', 'August',
          'September', 'October', 'November', 'December')
STATUS_ORDER = {'recommended': 0, 'alternative': 1, 'avoid': 2}
STATUS_LABELS = {'alternative': 'also used', 'avoid': 'avoid'}
PERIODS = {'classical': 'classical', 'post-classical': 'post-classical', 'late': 'late Latin',
           'medieval': 'medieval', 'renaissance': 'Renaissance', 'modern': 'modern', 'ours': 'our formation'}
PERIOD_TAGS = {'classical': 'Ancient Latin', 'post-classical': 'Ancient Latin', 'late': 'Late Latin',
               'medieval': 'Medieval & Renaissance', 'renaissance': 'Medieval & Renaissance',
               'modern': 'Neo-Latin', 'ours': 'Working formation'}
TAG_ORDER = ('Ancient Latin', 'Late Latin', 'Medieval & Renaissance', 'Neo-Latin', 'Working formation',
             'Quotations', 'Composed phrases', 'Draft')
RULING_KINDS = {'orthography': 'Spelling', 'quantity': 'Vowel length', 'usage': 'Usage', 'word': 'Word choices'}
RULING_STATUSES = ('current', 'provisional', 'withdrawn')
THEME_INIT = ("<script>\ntry {\n  document.documentElement.dataset.theme = "
              "localStorage.getItem('lexicon-theme') === 'light' ? 'light' : 'dark';\n} catch {}\n</script>")


def require(condition, message):
    if not condition:
        raise ValueError(message)


def fields(value, required, optional=()):
    require(isinstance(value, dict), 'Expected an object')
    require(set(required) <= value.keys(), f'Missing fields: {set(required) - value.keys()}')
    require(value.keys() <= set(required) | set(optional), f'Unknown fields: {value.keys() - set(required) - set(optional)}')


def string(value):
    require(isinstance(value, str) and bool(value.strip()), 'Expected nonempty text')
    return value


def strings(value, what):
    require(isinstance(value, list) and all(isinstance(v, str) and v.strip() for v in value), f'{what} must be a list of text')
    return value


def human_date(value):
    parts = [int(p) for p in value.split('-')]
    month = MONTHS[parts[1] - 1]
    return f'{parts[2]} {month} {parts[0]}' if len(parts) == 3 else f'{month} {parts[0]}'


class Fragment(HTMLParser):
    """Validate trusted editorial rich text; keep its spelling and markup intact."""
    tags = {'strong', 'span', 'em', 'code', 'a', 'p', 'details', 'summary', 'ul', 'li', 'br'}
    attrs = {'lang', 'class', 'href', 'target', 'rel'}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []
        self.links = []

    def handle_starttag(self, tag, attrs):
        require(tag in self.tags, f'Unsupported rich-text tag: {tag}')
        require(all(k in self.attrs for k, _ in attrs), f'Unsupported attributes on {tag}')
        for key, value in attrs:
            require(value is not None, f'Missing value for {key}')
            if key == 'href':
                require(value.startswith(('https://', 'http://', '#')), f'Unsupported link: {value}')
                self.links.append(value)
        if tag != 'br':
            self.stack.append(tag)

    def handle_endtag(self, tag):
        require(self.stack and self.stack.pop() == tag, f'Unbalanced rich text: {tag}')

    def handle_startendtag(self, tag, attrs):
        require(tag == 'br', 'Only br may be self-closing')
        self.handle_starttag(tag, attrs)

    def handle_comment(self, data):
        raise ValueError('Comments are not supported in entry rich text')


def rich(value):
    parser = Fragment()
    parser.feed(string(value))
    parser.close()
    require(not parser.stack, 'Unclosed rich-text tag')
    return value


# Grouped entries (data/entries) ------------------------------------------------

def render_block(block):
    require(isinstance(block, dict), 'Expected a block object')
    kind = block.get('type')
    if kind == 'list':
        fields(block, ('type', 'items'))
        require(isinstance(block['items'], list) and block['items'], 'Empty list')
        items = []
        for item in block['items']:
            fields(item, ('html',), ('class',))
            require(item.get('class', 'note') == 'note', 'Unsupported list-item class')
            attr = ' class="note"' if 'class' in item else ''
            items.append(f'<li{attr}>{rich(item["html"])}</li>')
        return '<ul>\n' + '\n'.join(items) + '\n</ul>'
    if kind == 'paragraph':
        fields(block, ('type', 'html'), ('class',))
        require(block.get('class', 'source-note') == 'source-note', 'Unsupported paragraph class')
        attr = ' class="source-note"' if 'class' in block else ''
        return f'<p{attr}>{rich(block["html"])}</p>'
    if kind == 'sources':
        fields(block, ('type', 'summary', 'paragraphs'))
        require(isinstance(block['paragraphs'], list) and block['paragraphs'], 'Empty sources')
        paragraphs = ''.join(f'<p>{rich(p)}</p>' for p in block['paragraphs'])
        return f'<details class="entry-sources"><summary>{escape(string(block["summary"]))}</summary>{paragraphs}</details>'
    raise ValueError(f'Unknown block type: {kind}')


def entry_html_id(entry):
    """Every card has a static ID: its anchor if it has one, otherwise its entry ID."""
    return entry.get('anchor') or entry['id']


def render_entry(entry, category):
    fields(entry, ('id', 'english', 'latin', 'tags', 'blocks'), ('anchor', 'keywords'))
    require(re.fullmatch(ENTRY_ID, string(entry['id'])), 'Invalid entry ID')
    anchor = entry.get('anchor')
    require(anchor is None or (re.fullmatch(r'[a-z][a-z0-9-]*', string(anchor)) and not re.fullmatch(ENTRY_ID, anchor)),
            'Invalid anchor')
    require(isinstance(entry['tags'], list), 'Tags must be a list')
    tags = ''.join(f'<span class="tag">{escape(string(t))}</span>' for t in entry['tags'])
    require(isinstance(entry['blocks'], list) and entry['blocks'], 'Entry must have content')
    body = '\n'.join(render_block(b) for b in entry['blocks'])
    require(isinstance(entry.get('keywords', ''), str), 'Keywords must be text')
    return (f'<article class="entry" id="{escape(entry_html_id(entry))}" data-entry data-entry-id="{entry["id"]}" '
            f'data-category="{category}" data-search="{escape(entry.get("keywords", ""), quote=True)}">\n'
            f'<header class="entry-head"><div><p class="eyebrow">{escape(string(entry["english"]))}</p>'
            f'<h3 lang="la">{escape(string(entry["latin"]))}</h3></div><div class="tags">{tags}</div></header>\n'
            f'<div class="entry-body">{body}</div>\n</article>')


# Rulings (data/rulings.json) -----------------------------------------------------

def load_rulings(root):
    path = root / 'data/rulings.json'
    items = json.loads(path.read_text(encoding='utf-8')) if path.exists() else []
    require(isinstance(items, list), 'data/rulings.json must be a list')
    rulings = {}
    for ruling in items:
        fields(ruling, ('id', 'kind', 'title', 'decision', 'date', 'by', 'status', 'html'), ('forms', 'history'))
        key = string(ruling['id'])
        require(re.fullmatch(SLUG, key), f'Invalid ruling ID: {key}')
        require(key not in rulings, f'Duplicate ruling: {key}')
        require(ruling['kind'] in RULING_KINDS, f'Invalid ruling kind: {key}')
        require(ruling['status'] in RULING_STATUSES, f'Invalid ruling status: {key}')
        require(re.fullmatch(DATE, string(ruling['date'])), f'Invalid ruling date: {key}')
        string(ruling['title']), string(ruling['by']), rich(ruling['decision']), rich(ruling['html'])
        strings(ruling.get('forms', []), f'Forms of ruling {key}')
        require(isinstance(ruling.get('history', []), list), f'History of ruling {key} must be a list')
        for change in ruling.get('history', []):
            fields(change, ('date', 'html'))
            require(re.fullmatch(DATE, string(change['date'])), f'Invalid history date in ruling {key}')
            rich(change['html'])
        rulings[key] = ruling
    return rulings


# Concept records (data/concepts) -------------------------------------------------

def check_notes(item, notes, where):
    keys = strings(item.get('notes', []), f'Notes in {where}')
    require(len(keys) == len(set(keys)), f'Repeated note in {where}')
    require(all(k in notes for k in keys), f'Unknown note in {where}: {set(keys) - notes.keys()}')
    return keys


def load_records(root, categories, legacy, rulings):
    folder = root / 'data/concepts'
    records = {}
    for path in sorted(folder.glob('*.json')) if folder.exists() else []:
        record = json.loads(path.read_text(encoding='utf-8'))
        fields(record, ('id', 'english', 'domain', 'terms', 'sources', 'review'),
               ('sense', 'also', 'wikidata', 'audience', 'phrases', 'notes', 'related', 'replaces'))
        key = string(record['id'])
        where = f'concept {key}'
        require(re.fullmatch(SLUG, key) and path.stem == key, f'Concept ID must be a slug matching its file name: {path.name}')
        string(record['english'])
        if 'sense' in record:
            string(record['sense'])
        strings(record.get('also', []), f'Also in {where}')
        require(record['domain'] in categories, f'Unknown domain in {where}')
        require(re.fullmatch(r'Q[1-9][0-9]*', record.get('wikidata', 'Q1')), f'Invalid Wikidata item in {where}')
        require(record.get('audience', 'child') in ('child', 'adult'), f'Invalid audience in {where}')
        notes = record.get('notes', {})
        require(isinstance(notes, dict), f'Notes in {where} must be an object')
        for name, note in notes.items():
            require(re.fullmatch(SLUG, name), f'Invalid note key in {where}: {name}')
            fields(note, ('html',), ('ruling',))
            rich(note['html'])
            if 'ruling' in note:
                require(note['ruling'] in rulings, f'Unknown ruling in {where}: {note["ruling"]}')
        used = []
        require(isinstance(record['terms'], list) and record['terms'], f'No terms in {where}')
        require(any(t.get('status') == 'recommended' for t in record['terms']), f'No recommended term in {where}')
        for term in record['terms']:
            fields(term, ('latin', 'status', 'period'), ('gloss', 'register', 'evidence', 'comment', 'notes'))
            string(term['latin'])
            require(term['status'] in STATUS_ORDER, f'Invalid status in {where}')
            require(term['period'] in PERIODS, f'Invalid period in {where}')
            for name in ('gloss',):
                if name in term:
                    string(term[name])
            for name in ('register', 'comment'):
                if name in term:
                    rich(term[name])
            for evidence in strings(term.get('evidence', []), f'Evidence in {where}'):
                rich(evidence)
            used += check_notes(term, notes, where)
        require(isinstance(record.get('phrases', []), list), f'Phrases in {where} must be a list')
        for phrase in record.get('phrases', []):
            fields(phrase, ('latin', 'english', 'source'), ('notes',))
            string(phrase['latin']), string(phrase['english']), rich(phrase['source'])
            used += check_notes(phrase, notes, where)
        require(set(notes) <= set(used), f'Unused notes in {where}: {set(notes) - set(used)}')
        strings(record.get('related', []), f'Related in {where}')
        for source in strings(record['sources'], f'Sources in {where}'):
            rich(source)
        require(record['sources'], f'No sources in {where}')
        fields(record['review'], ('status', 'date', 'by'))
        require(record['review']['status'] in ('draft', 'reviewed'), f'Invalid review status in {where}')
        require(re.fullmatch(DATE, string(record['review']['date'])), f'Invalid review date in {where}')
        string(record['review']['by'])
        for old in strings(record.get('replaces', []), f'Replaces in {where}'):
            require(re.fullmatch(r'[a-z][a-z0-9-]*', old), f'Invalid replaced ID in {where}: {old}')
            require(old not in legacy and old not in {entry_html_id(e) for e in legacy.values()},
                    f'{where} replaces {old}, which still exists')
        records[key] = record
    replaced = [old for r in records.values() for old in r.get('replaces', [])]
    require(len(replaced) == len(set(replaced)), 'An old entry is replaced by two concepts')
    for record in records.values():
        for target in record.get('related', []):
            require(target in records or target in legacy, f'Unknown related target in concept {record["id"]}: {target}')
            require(target != record['id'], f'Concept {record["id"]} relates to itself')
    return records


def ordered_terms(record):
    return sorted(record['terms'], key=lambda t: STATUS_ORDER[t['status']])


def note_numbers(record):
    numbers = {}
    for item in ordered_terms(record) + record.get('phrases', []):
        for key in item.get('notes', []):
            numbers.setdefault(key, len(numbers) + 1)
    return numbers


def record_tags(record):
    tags = {PERIOD_TAGS[t['period']] for t in record['terms']}
    phrases = record.get('phrases', [])
    if any(p['source'] != 'composed' for p in phrases) or any('lang="la"' in e for t in record['terms'] for e in t.get('evidence', [])):
        tags.add('Quotations')
    if any(p['source'] == 'composed' for p in phrases):
        tags.add('Composed phrases')
    if record['review']['status'] == 'draft':
        tags.add('Draft')
    return [t for t in TAG_ORDER if t in tags]


def record_heading(record):
    return ' · '.join(t['latin'] for t in record['terms'] if t['status'] == 'recommended')


def record_english(record):
    return record['english'] + (f' · {record["sense"]}' if 'sense' in record else '')


class Links:
    """Where links point from a given page: the index ('') or a concept page ('c/')."""
    def __init__(self, site, on_concept_page):
        self.site, self.up = site, '../' if on_concept_page else ''
        self.concept_page = on_concept_page

    def concept(self, key):
        return f'{key}.html' if self.concept_page else f'#c-{key}'

    def entry(self, key):
        target = entry_html_id(self.site['legacy'][key])
        return f'{self.up}index.html#{target}' if self.concept_page else f'#{target}'

    def ruling(self, key):
        return f'{self.up}rulings.html#r-{key}'

    def label(self, key):
        if key in self.site['records']:
            return escape(self.site['records'][key]['english'])
        return escape(self.site['legacy'][key]['english'].split(':')[0].strip())

    def related(self, key):
        return self.concept(key) if key in self.site['records'] else self.entry(key)


def render_record(record, site, on_concept_page=False):
    key, links = record['id'], Links(site, on_concept_page)
    numbers = note_numbers(record)

    def refs(item):
        return ''.join(f'<sup class="fn-ref"><a href="#fn-{key}-{numbers[n]}" aria-label="Note {numbers[n]}">{numbers[n]}</a></sup>'
                       for n in item.get('notes', []))

    lines = []
    for term in ordered_terms(record):
        register = f' <span class="register">({term["register"]})</span>' if 'register' in term else ''
        status = (f' <span class="pill status-{term["status"]}">{STATUS_LABELS[term["status"]]}</span>'
                  if term['status'] != 'recommended' else '')
        evidence = f' ({"; ".join(term["evidence"])})' if term.get('evidence') else ''
        comment = f' {term["comment"]}' if 'comment' in term else ''
        lines.append(f'<li class="term" data-status="{term["status"]}"><strong lang="la">{escape(term["latin"])}</strong>'
                     f' — {escape(term.get("gloss", record["english"]))}{register}'
                     f' <span class="pill period">{PERIODS[term["period"]]}</span>{status}{evidence}{refs(term)}{comment}</li>')
    for phrase in record.get('phrases', []):
        source = ' <span class="pill">composed</span>' if phrase['source'] == 'composed' else f' ({phrase["source"]})'
        lines.append(f'<li class="phrase"><strong lang="la">{escape(phrase["latin"])}</strong>'
                     f' — {escape(phrase["english"])}{source}{refs(phrase)}</li>')
    body = '<ul>\n' + '\n'.join(lines) + '\n</ul>'
    if record.get('related'):
        body += ('<p class="related">See also: '
                 + ', '.join(f'<a href="{links.related(r)}">{links.label(r)}</a>' for r in record['related']) + '.</p>')
    if numbers:
        notes = []
        for name, number in numbers.items():
            note = record['notes'][name]
            ruling = ''
            if 'ruling' in note:
                ruling = (f' <a class="ruling-link" href="{links.ruling(note["ruling"])}">'
                          f'Ruling: {escape(site["rulings"][note["ruling"]]["title"])}</a>')
            notes.append(f'<li id="fn-{key}-{number}">{note["html"]}{ruling}</li>')
        body += '<ol class="footnotes" aria-label="Notes">' + ''.join(notes) + '</ol>'
    review = record['review']
    state = (f'Reviewed by {escape(review["by"])}, {human_date(review["date"])}.' if review['status'] == 'reviewed'
             else f'Draft of {human_date(review["date"])}, not yet reviewed.')
    body += ('<details class="entry-sources"><summary>Sources &amp; evidence</summary>'
             + ''.join(f'<p>{s}</p>' for s in record['sources']) + f'<p>{state}</p></details>')
    anchors = ''.join(f'<span class="legacy-anchor" id="{escape(old)}"></span>' for old in record.get('replaces', []))
    tags = ''.join(f'<span class="tag">{escape(t)}</span>' for t in record_tags(record))
    page = '' if on_concept_page else f'<p class="record-meta"><a href="c/{key}.html">Page for this word</a></p>'
    search = ' '.join(record.get('also', []))
    html_id = '' if on_concept_page else f' id="c-{key}"'
    return (f'<article class="entry record"{html_id} data-entry data-record data-entry-id="c-{key}" '
            f'data-category="{record["domain"]}" data-search="{escape(search, quote=True)}">{anchors}\n'
            f'<header class="entry-head"><div><p class="eyebrow">{escape(record_english(record))}</p>'
            f'<h3 lang="la">{escape(record_heading(record))}</h3></div><div class="tags">{tags}</div></header>\n'
            f'<div class="entry-body">{body}</div>\n{page}</article>')


def plain(text):
    return re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', text)).strip()


def page_shell(title, description, canonical, up, body):
    return (GENERATED + '<!doctype html>\n<html lang="en" data-theme="dark">\n<head>\n<meta charset="utf-8">\n'
            '<meta name="viewport" content="width=device-width, initial-scale=1">\n'
            '<meta name="color-scheme" content="light dark">\n'
            f'<title>{escape(title)}</title>\n<meta name="description" content="{escape(description, quote=True)}">\n'
            f'<link rel="canonical" href="{SITE_URL}{canonical}">\n{THEME_INIT}\n'
            f'<link rel="stylesheet" href="{up}assets/lexicon.css">\n</head>\n<body class="subpage">\n'
            f'<header class="hero wrap"><div class="brand"><p class="site-name"><a href="{up}index.html" lang="la">{SITE_NAME}</a></p>'
            '<p class="brand-note">Everyday English–Latin</p></div>'
            f'<p class="about-link"><a href="{up}index.html">Search the lexicon</a></p></header>\n'
            f'<main class="wrap page-main">\n{body}\n</main>\n'
            f'<footer><div class="wrap"><p><a href="{up}how-we-decide.html">How we decide</a> · <a href="{up}rulings.html">Rulings</a> · '
            f'<a href="{up}index.html">Search the lexicon</a> · '
            '<a href="https://github.com/jhwheeler/lexicon-latinitatis-cotidianae">Source and history</a></p></div></footer>\n'
            '</body>\n</html>\n')


def render_concept_page(record, site, categories):
    english, heading = record['english'], record_heading(record)
    lemma = next(t['latin'] for t in ordered_terms(record)).split(',')[0]
    domain = categories[record['domain']]
    body = (f'<nav class="breadcrumb" aria-label="Topic"><a href="../index.html#{record["domain"]}">'
            f'<span lang="la">{escape(domain["latin"])}</span> · {escape(domain["english"])}</a></nav>\n'
            f'<h1 class="page-title">{escape(english)} <span class="page-title-note">in Latin</span></h1>\n'
            + render_record(record, site, on_concept_page=True))
    return page_shell(f'{english} in Latin: {lemma} · {SITE_NAME}',
                      f'How to say “{english}” in Latin: {heading}. With the period of each form, its sources and examples.',
                      f'c/{record["id"]}.html', '../', body)


def render_rulings(site):
    cited = {}
    for record in sorted(site['records'].values(), key=lambda r: r['english']):
        for note in record.get('notes', {}).values():
            if 'ruling' in note and record['id'] not in cited.setdefault(note['ruling'], []):
                cited[note['ruling']].append(record['id'])
    sections = []
    for kind, label in RULING_KINDS.items():
        group = sorted((r for r in site['rulings'].values() if r['kind'] == kind), key=lambda r: (r['date'], r['id']))
        if not group:
            continue
        cards = []
        for ruling in group:
            key = ruling['id']
            forms = (f'<p class="ruling-forms">Forms: ' + ', '.join(f'<span lang="la">{escape(f)}</span>' for f in ruling['forms'])
                     + '</p>') if ruling.get('forms') else ''
            history = ('<ul class="ruling-history">' + ''.join(f'<li>{human_date(h["date"])}: {h["html"]}</li>' for h in ruling['history'])
                       + '</ul>') if ruling.get('history') else ''
            used = (f'<p class="ruling-cited">Cited in: ' + ', '.join(
                f'<a href="c/{c}.html">{escape(site["records"][c]["english"])}</a>' for c in cited[key]) + '</p>') if key in cited else ''
            cards.append(f'<article class="ruling" id="r-{key}"><header><h3>{escape(ruling["title"])}</h3>'
                         f'<p class="ruling-meta"><span class="pill status-{ruling["status"]}">{ruling["status"]}</span> '
                         f'{human_date(ruling["date"])} · {escape(ruling["by"])}</p></header>'
                         f'<p class="ruling-decision">{ruling["decision"]}</p><p>{ruling["html"]}</p>{forms}{history}{used}</article>')
        sections.append(f'<section class="ruling-group" id="rulings-{kind}"><h2>{label}</h2>' + '\n'.join(cards) + '</section>')
    return '\n'.join(sections)


class Document(HTMLParser):
    """Collect element IDs and local links of one generated page."""
    def __init__(self):
        super().__init__()
        self.ids = set()
        self.links = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            require(attrs['id'] not in self.ids, f'Duplicate HTML ID: {attrs["id"]}')
            self.ids.add(attrs['id'])
        href = attrs.get('href') or ''
        if href and not href.startswith(('https://', 'http://', 'mailto:')):
            self.links.append(href)


def check_links(outputs):
    """Every local link must reach a generated page and, with a fragment, an ID on it."""
    documents = {}
    for path, text in outputs.items():
        if path.endswith('.html'):
            doc = Document()
            doc.feed(text)
            documents[path] = doc
    broken = []
    for path, doc in documents.items():
        for link in doc.links:
            target, _, fragment = link.partition('#')
            target = posixpath.normpath(posixpath.join(posixpath.dirname(path), target)) if target else path
            if target not in outputs or (fragment and (target not in documents or fragment not in documents[target].ids)):
                broken.append(f'{path} → {link}')
    require(not broken, f'Broken fragment links: {broken[:8]}')


def load_site(root):
    catalog = json.loads((root / 'data/catalog.json').read_text(encoding='utf-8'))
    fields(catalog, ('version', 'categories', 'filters'))
    require(catalog['version'] == 1, 'Unsupported catalog version')
    require(isinstance(catalog['categories'], list) and catalog['categories'], 'No categories')
    categories, legacy, anchors = {}, {}, set()
    entries = {}
    for category in catalog['categories']:
        fields(category, ('id', 'english', 'latin'), ('aliases',))
        key = string(category['id'])
        require(re.fullmatch(r'[a-z][a-z0-9-]*', key), 'Invalid category ID')
        for alias in strings(category.get('aliases', []), f'Aliases of category {key}'):
            require(re.fullmatch(r'[a-z][a-z0-9-]*', alias), f'Invalid alias of category {key}: {alias}')
        require(key not in categories and key != 'all', f'Duplicate/reserved category: {key}')
        categories[key] = category
        items = json.loads((root / f'data/entries/{key}.json').read_text(encoding='utf-8'))
        require(isinstance(items, list), f'Entries of {key} must be a list')
        for entry in items:
            require(isinstance(entry, dict) and entry.get('id') not in legacy, f'Duplicate entry: {entry.get("id")}')
            if entry.get('anchor'):
                require(entry['anchor'] not in anchors, 'Duplicate entry anchor')
                anchors.add(entry['anchor'])
            legacy[entry['id']] = entry
        entries[key] = items
    files = {p.stem for p in (root / 'data/entries').glob('*.json')}
    require(files == set(categories), f'Unlisted or missing category files: {files ^ set(categories)}')
    rulings = load_rulings(root)
    site = {'catalog': catalog, 'categories': categories, 'entries': entries, 'legacy': legacy, 'rulings': rulings}
    site['records'] = load_records(root, categories, legacy, rulings)
    for key in categories:
        require(entries[key] or any(r['domain'] == key for r in site['records'].values()), f'Empty category: {key}')
    return site


def render_index(root, site):
    sections = []
    for key, category in site['categories'].items():
        cards = [render_entry(entry, key) for entry in site['entries'][key]]
        records = sorted((r for r in site['records'].values() if r['domain'] == key), key=lambda r: (r['english'].lower(), r['id']))
        cards += [render_record(r, site) for r in records]
        aliases = ''.join(f'<span class="legacy-anchor" id="{a}"></span>' for a in category.get('aliases', []))
        sections.append(f'<section class="category" data-category-section="{key}" id="{key}">{aliases}'
                        '<div class="category-heading"><div>'
                        f'<p class="eyebrow">{escape(string(category["english"]))}</p>'
                        f'<h2 lang="la">{escape(string(category["latin"]))}</h2></div>'
                        f'<span class="category-count">{len(cards)} entries</span></div>'
                        '<div class="entries">' + '\n'.join(cards) + '</div></section>')
    filters = site['catalog']['filters']
    require(isinstance(filters, list) and all(isinstance(f, str) for f in filters), 'Invalid filters')
    require(len(filters) == len(set(filters)) and set(filters) == set(site['categories']) | {'all'}, 'Filters must cover every category once')
    labels = {k: c['latin'] for k, c in site['categories'].items()} | {'all': 'Omnia'}
    chips = ''.join(f'<button class="chip" type="button" data-filter="{key}" '
                    f'aria-pressed="{str(key == "all").lower()}"'
                    + ('' if key == 'all' else ' lang="la"')
                    + f'>{escape(string(labels[key]))}</button>' for key in filters)
    replacements = {'styles': (root / 'src/styles.css').read_text(encoding='utf-8'),
                    'search': (root / 'src/search.js').read_text(encoding='utf-8'),
                    'filters': chips, 'entries': '\n'.join(sections),
                    'entry_count': str(len(site['legacy'])), 'record_count': str(len(site['records']))}
    return fill(root / 'src/page.html', replacements)


def fill(path, replacements):
    page = path.read_text(encoding='utf-8')
    for name, value in replacements.items():
        token = '{{' + name + '}}'
        require(token in page, f'Missing template token: {token}')
        page = page.replace(token, value)
    require(not re.search(r'\{\{\w+\}\}', page), 'Unknown template token')
    return page


def render_sitemap(site):
    pages = ['', 'how-we-decide.html', 'rulings.html'] + [f'c/{key}.html' for key in sorted(site['records'])]
    return ('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
            + ''.join(f'<url><loc>{SITE_URL}{page}</loc></url>\n' for page in pages) + '</urlset>\n')


def build_site(root=ROOT):
    """Return every generated file as {path relative to the repository root: text}."""
    site = load_site(root)
    outputs = {'index.html': render_index(root, site)}
    outputs['how-we-decide.html'] = fill(root / 'src/how-we-decide.html', {
        'ruling_count': str(len(site['rulings'])), 'theme': THEME_INIT})
    outputs['rulings.html'] = fill(root / 'src/rulings.html', {
        'rulings': render_rulings(site), 'ruling_count': str(len(site['rulings'])), 'theme': THEME_INIT})
    for key, record in sorted(site['records'].items()):
        outputs[f'c/{key}.html'] = render_concept_page(record, site, site['categories'])
    outputs['sitemap.xml'] = render_sitemap(site)
    outputs['assets/lexicon.css'] = (root / 'src/styles.css').read_text(encoding='utf-8')
    check_links(outputs)
    return outputs


def build(root=ROOT):
    """The main page alone (kept for the converter and its tests)."""
    return build_site(root)['index.html']


def stale(root, outputs):
    return sorted(str(p.relative_to(root)) for p in (root / 'c').glob('*.html')
                  if str(PurePosixPath(p.relative_to(root))) not in outputs) if (root / 'c').exists() else []


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--check', action='store_true', help='Fail if any generated file needs rebuilding')
    args = parser.parse_args()
    try:
        outputs = build_site()
        if args.check:
            changed = [p for p, text in outputs.items()
                       if not (ROOT / p).exists() or (ROOT / p).read_text(encoding='utf-8') != text]
            leftover = stale(ROOT, outputs)
            require(not changed and not leftover,
                    f'Generated files are stale ({", ".join(changed + leftover)}); run python3 scripts/build.py and commit the result')
            print(f'Generated files are up to date ({len(outputs)} files).')
        else:
            for path in stale(ROOT, outputs):
                (ROOT / path).unlink()
            for path, text in outputs.items():
                (ROOT / path).parent.mkdir(parents=True, exist_ok=True)
                (ROOT / path).write_text(text, encoding='utf-8')
            print(f'Built index.html and {len(outputs) - 1} other files.')
    except (ValueError, KeyError, TypeError, OSError) as error:
        print(f'Build failed: {error}', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
