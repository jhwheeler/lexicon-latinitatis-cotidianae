    return [e for e in endings if re.search(r'(?:r|ris|re|tur|mur|min[iī]|ntur|r[iī])$', e)
            or (e in ('i', 'ī') and cls in ('v3', 'v3i')) or re.match(rf'(?:{vowel}|{vowel[:-1]}[āē]|u)(?:ns$|n[td](?![oō]?$))', e)]


