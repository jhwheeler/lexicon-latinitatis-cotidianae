def other_senses(site):
    """{record id: [(other record id, label)]}: the other entries that answer to the same English
    headword, so that an entry does not read as if its sense were the only one (Jack, 16 November
    2026, on "charge", whose entry is the battery's: "it's as if you only charge batteries. charge
    can mean many things. either it needs multiple entries or multiple sections in the same entry,
    which is more like how proper dictionaries do it"). The lexicon has one record per sense, so
    the senses are other records: those with the same headword (labelled by their `sense`), then
    those that list the headword under `also`, bare or with a sense in brackets ("charge (in
    battle)" under attack, labelled "in battle"; "charge" under price, labelled "see price").
    Worked out once for the site."""
    if '_senses' not in site:
        index = {}
        for key, record in site['records'].items():
            index.setdefault(record['english'].lower(), []).append((0, key, record.get('sense')))
            for also in record.get('also', []):
                bracketed = re.fullmatch(r'(.+?)\s*\(([^)]+)\)', also)
                base, label = (bracketed.group(1), bracketed.group(2)) if bracketed else (also, None)
                index.setdefault(base.lower(), []).append((1, key, label))
        senses = {}
        for key, record in site['records'].items():
            seen, found = {key}, []
            for _, other, label in sorted(index[record['english'].lower()], key=lambda row: row[0]):
                if other not in seen:
                    seen.add(other)
                    found.append((other, label))
            if found:
                senses[key] = found
        site['_senses'] = senses
    return site['_senses']


def render_concept(record, site):
    """A concept's own page: the headword line, the recommended Latin with its grammar and usage,
    the examples (filterable by source), the other words, and the margin of periods, evidence and
    notes beside the lines they explain."""
    key, links = record['id'], Links(site, 'concept')
    numbers, placed = note_numbers(record), set()

    def refs(item):
        return ''.join(f'<sup class="fn"><a href="#fn-{key}-{numbers[n]}" aria-label="Note {numbers[n]}">{numbers[n]}</a></sup>'
                       for n in item.get('notes', []))

    def notes(item):
        out = []
        for name in item.get('notes', []):
            if name in placed:
                continue
            placed.add(name)
            note, ruling = record['notes'][name], ''
            if 'ruling' in note:
                found = site['rulings'][note['ruling']]
                state = f' ({found["status"]})' if found['status'] != 'current' else ''
                ruling = f' <a class="ruling-link" href="{links.ruling(note["ruling"])}">Ruling: {escape(found["title"])}</a>{state}.'
            out.append(f'<aside class="side note" id="fn-{key}-{numbers[name]}"><p><span class="n">{numbers[name]}</span>'
                       f'{note_html(note)}{ruling}</p></aside>')
        return ''.join(out)

    def labels(term):
        status = (f'<span class="lab status-{term["status"]}">{STATUS_LABELS[term["status"]]}</span> · '
                  if term['status'] != 'recommended' else '')
        return status + f'<span class="lab">{PERIODS[term["period"]]}</span>'

    terms = ordered_terms(record)
    main, others = terms[0], terms[1:]
    domain = site['categories'][record['domain']]
    pos = pos_label(record)
    kinds = ' · '.join(f'<a href="../k/{key}.html">{escape(site["categories"][key]["english"])}</a>'
                       for key in [record['domain']] + record.get('also_under', []))
    parts = [f'<p class="kind">{kinds}</p>',
             f'<h1 class="hw">{escape(record["english"])}' + (f' <span class="pos">{escape(pos)}</span>' if pos else '') + '</h1>']
    if 'sense' in record:
        parts.append(f'<p class="sense">{escape(record["sense"])}</p>')
    if record.get('also'):
        parts.append(f'<p class="also">also {escape(", ".join(record["also"]))}</p>')
    senses = other_senses(site).get(record['id'])
    if senses:
        def sense(other, label):
            there = site['records'][other]
            name = label or (there.get('sense') if there['english'].lower() == record['english'].lower() else None)
            return (f'<a href="{links.concept(other)}">{escape(name or "see " + there["english"])}</a> '
                    f'<span lang="la">{escape(term_head(ordered_terms(there)[0]["latin"]))}</span>')
        parts.append('<p class="senses"><span class="sc">Other senses</span>' + ' · '.join(sense(*found) for found in senses) + '</p>')

    head, rest = links.latin(main['latin'])
    evidence = ('<p>' + '<br>'.join(main['evidence']) + '</p>') if main.get('evidence') else ''
    gloss = main.get('gloss', '')
    block = [f'<aside class="side"><p>{labels(main)}</p>{evidence}</aside>', notes(main),
             f'<p class="lemma" lang="la">{ours_mark(main)}<b>{head}</b>{refs(main)}{rest}</p>']
    if grammar_html(main):
        block.append(f'<p class="gram">{grammar_html(main)}</p>')
    if gloss and gloss.strip().lower() != record['english'].strip().lower():
        block.append(f'<p class="def">{escape(gloss)}</p>')
    if 'register' in main:
        block.append(f'<p class="meta-line register">({main["register"]})</p>')
    if 'comment' in main:
        block.append(f'<p class="comment">{main["comment"]}</p>')
    block.append(concept_family_line(record, site, links))
    parts.append('<section class="term has-side" aria-label="The Latin">' + ''.join(block) + '</section>')

    # The other words come before the examples: the examples illustrate every term of the record,
    # not only the first, so all the terms must be on the page before them (Jack, 11 November 2026).
    if others:
        items = []
        for term in others:
            head, rest = links.latin(term['latin'])
            side = notes(term)
            meta = term_meta(term, linked=True)
            gloss = f'<span class="gloss" lang="en"> — {escape(term["gloss"])}</span>' if term.get('gloss') else ''
            item = [side, f'<p class="lemma" lang="la">{ours_mark(term)}<b>{head}</b>{refs(term)}{rest}{gloss}</p>',
                    f'<p class="meta-line">{meta}</p>']
            if 'register' in term:
                item.append(f'<p class="meta-line register">({term["register"]})</p>')
            if 'comment' in term:
                item.append(f'<p class="comment">{term["comment"]}</p>')
            items.append('<li' + (' class="has-side"' if side else '') + '>' + ''.join(item) + '</li>')
        parts.append(f'<section class="sec" aria-labelledby="ow-{key}-h"><div class="sec-head"><h2 id="ow-{key}-h">Other words</h2></div>'
                     '<ul class="words">' + ''.join(items) + '</ul></section>')

    phrases = record.get('phrases', [])
    if phrases:
        kinds = {'composed' if composed(p) else 'author' for p in phrases}
        control = ''
        if len(kinds) == 2:
            control = (f'<div class="filter" role="group" aria-label="Show examples" data-example-filter="ex-{key}" hidden>'
                       '<button type="button" data-show="all" aria-pressed="true">All</button>'
                       '<button type="button" data-show="author" aria-pressed="false">From authors</button>'
                       '<button type="button" data-show="composed" aria-pressed="false">Composed</button></div>')
        items = []
        for phrase in phrases:
            kind = 'composed' if composed(phrase) else 'author'
            source = ('<span class="src composed">composed</span>' if kind == 'composed'
                      else f'<span class="src">{phrase["source"]}</span>')
            side = notes(phrase)
            items.append(f'<li data-source="{kind}"' + (' class="has-side"' if side else '') + f'>{side}'
                         f'<p class="la tap" lang="la">{links.text(phrase["latin"])}{refs(phrase)}</p>'
                         f'<p class="en">{escape(phrase["english"])}{source}</p></li>')
        parts.append(f'<section class="sec" aria-labelledby="ex-{key}-h"><div class="sec-head"><h2 id="ex-{key}-h">Examples</h2>'
                     f'{control}</div><ul class="ex" id="ex-{key}">' + ''.join(items) + '</ul></section>')

    if record.get('related'):
        parts.append('<p class="see">See also ' + ', '.join(
            f'<a href="{links.related(r)}">{links.label(r)}</a>' for r in record['related']) + '.</p>')
    sources = shown_sources(record)
    # What is true of every entry's sources (what "Lewis & Short" after a quotation means, which
    # editions the authors are quoted from) is said once, on the policy page; an entry that has
    # sources leads there.
    parts.append('<footer class="c-sources">'
                 + (f'<p><span class="sc">Sources</span>{sources[0]}</p>' if sources else '')
                 + ''.join(f'<p>{s}</p>' for s in sources[1:]) + f'<p class="review-state">{review_state(record["review"], links.up)}</p>'
                 + (f'<p class="how-sources"><a href="{links.up}{SOURCES_SECTION}">{SOURCES_LINK}</a></p>' if sources else '')
                 + suggest_link(f'c/{record["id"]}.html', record['english'] + (f' ({record["sense"]})' if 'sense' in record else ''))
                 + '</footer>')
    return concept_article(record) + '\n' + '\n'.join(parts) + '\n</article>'


