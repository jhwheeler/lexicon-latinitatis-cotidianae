def require(condition, message):
    if not condition:
        raise ValueError(message)


def fields(value, required, optional=()):
    require(isinstance(value, dict), 'Expected an object')
    require(set(required) <= value.keys(), f'Missing fields: {set(required) - value.keys()}')
    require(value.keys() <= set(required) | set(optional), f'Unknown fields: {value.keys() - set(required) - set(optional)}')


def string(value):
    require(isinstance(value, str) and bool(value.strip()), 'Expected nonempty text')
    return value


def strings(value, what):
    require(isinstance(value, list) and all(isinstance(v, str) and v.strip() for v in value), f'{what} must be a list of text')
    return value


def human_date(value):
    parts = [int(p) for p in value.split('-')]
    month = MONTHS[parts[1] - 1]
    return f'{parts[2]} {month} {parts[0]}' if len(parts) == 3 else f'{month} {parts[0]}'


class Fragment(HTMLParser):
    """Validate trusted editorial rich text; keep its spelling and markup intact."""
    tags = {'strong', 'span', 'em', 'code', 'a', 'p', 'details', 'summary', 'ul', 'li', 'br'}
    attrs = {'lang', 'class', 'href', 'target', 'rel'}

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.stack = []
        self.links = []

    def handle_starttag(self, tag, attrs):
        require(tag in self.tags, f'Unsupported rich-text tag: {tag}')
        require(all(k in self.attrs for k, _ in attrs), f'Unsupported attributes on {tag}')
        for key, value in attrs:
            require(value is not None, f'Missing value for {key}')
            if key == 'href':
                require(value.startswith(('https://', 'http://', '#')), f'Unsupported link: {value}')
                self.links.append(value)
        if tag != 'br':
            self.stack.append(tag)

    def handle_endtag(self, tag):
        require(self.stack and self.stack.pop() == tag, f'Unbalanced rich text: {tag}')

    def handle_startendtag(self, tag, attrs):
        require(tag == 'br', 'Only br may be self-closing')
        self.handle_starttag(tag, attrs)

    def handle_comment(self, data):
        raise ValueError('Comments are not supported in entry rich text')


def rich(value):
    parser = Fragment()
    parser.feed(string(value))
    parser.close()
    require(not parser.stack, 'Unclosed rich-text tag')
    return value


# Grouped entries (data/entries) ------------------------------------------------

def render_block(block):
    require(isinstance(block, dict), 'Expected a block object')
    kind = block.get('type')
    if kind == 'list':
        fields(block, ('type', 'items'))
        require(isinstance(block['items'], list) and block['items'], 'Empty list')
        items = []
        for item in block['items']:
            fields(item, ('html',), ('class',))
            require(item.get('class', 'note') == 'note', 'Unsupported list-item class')
            attr = ' class="note"' if 'class' in item else ''
            items.append(f'<li{attr}>{rich(item["html"])}</li>')
        return '<ul>\n' + '\n'.join(items) + '\n</ul>'
    if kind == 'paragraph':
        fields(block, ('type', 'html'), ('class',))
        require(block.get('class', 'source-note') == 'source-note', 'Unsupported paragraph class')
        attr = ' class="source-note"' if 'class' in block else ''
        return f'<p{attr}>{rich(block["html"])}</p>'
    if kind == 'sources':
        fields(block, ('type', 'summary', 'paragraphs'))
        require(isinstance(block['paragraphs'], list) and block['paragraphs'], 'Empty sources')
        paragraphs = ''.join(f'<p>{rich(p)}</p>' for p in block['paragraphs'])
        return f'<details class="entry-sources"><summary>{escape(string(block["summary"]))}</summary>{paragraphs}</details>'
    raise ValueError(f'Unknown block type: {kind}')


def entry_html_id(entry):
    """Every card has a static ID: its anchor if it has one, otherwise its entry ID."""
    return entry.get('anchor') or entry['id']


def render_entry(entry, category):
    fields(entry, ('id', 'english', 'latin', 'tags', 'blocks'), ('anchor', 'keywords'))
    require(re.fullmatch(ENTRY_ID, string(entry['id'])), 'Invalid entry ID')
    anchor = entry.get('anchor')
    require(anchor is None or (re.fullmatch(r'[a-z][a-z0-9-]*', string(anchor)) and not re.fullmatch(ENTRY_ID, anchor)),
            'Invalid anchor')
    require(isinstance(entry['tags'], list), 'Tags must be a list')
    tags = ''.join(f'<span class="tag">{escape(string(t))}</span>' for t in entry['tags'])
    require(isinstance(entry['blocks'], list) and entry['blocks'], 'Entry must have content')
    body = '\n'.join(render_block(b) for b in entry['blocks'])
    require(isinstance(entry.get('keywords', ''), str), 'Keywords must be text')
    return (f'<article class="entry" id="{escape(entry_html_id(entry))}" data-entry data-entry-id="{entry["id"]}" '
            f'data-category="{category}" data-search="{escape(entry.get("keywords", ""), quote=True)}">\n'
            f'<header class="entry-head"><div><p class="eyebrow">{escape(string(entry["english"]))}</p>'
            f'<h3 lang="la">{escape(string(entry["latin"]))}</h3></div><div class="tags">{tags}</div></header>\n'
            f'<div class="entry-body">{body}</div>\n</article>')


# Rulings (data/rulings.json) -----------------------------------------------------

def load_rulings(root):
    path = root / 'data/rulings.json'
    items = json.loads(path.read_text(encoding='utf-8')) if path.exists() else []
    require(isinstance(items, list), 'data/rulings.json must be a list')
    rulings = {}
    for ruling in items:
        fields(ruling, ('id', 'kind', 'title', 'decision', 'date', 'by', 'status', 'html'), ('forms', 'history'))
        key = string(ruling['id'])
        require(re.fullmatch(SLUG, key), f'Invalid ruling ID: {key}')
        require(key not in rulings, f'Duplicate ruling: {key}')
        require(ruling['kind'] in RULING_KINDS, f'Invalid ruling kind: {key}')
        require(ruling['status'] in RULING_STATUSES, f'Invalid ruling status: {key}')
        require(re.fullmatch(DATE, string(ruling['date'])), f'Invalid ruling date: {key}')
        string(ruling['title']), string(ruling['by']), rich(ruling['decision']), rich(ruling['html'])
        strings(ruling.get('forms', []), f'Forms of ruling {key}')
        require(isinstance(ruling.get('history', []), list), f'History of ruling {key} must be a list')
        for change in ruling.get('history', []):
            fields(change, ('date', 'html'))
            require(re.fullmatch(DATE, string(change['date'])), f'Invalid history date in ruling {key}')
            rich(change['html'])
        rulings[key] = ruling
    return rulings


# Concept records (data/concepts) -------------------------------------------------

def check_notes(item, notes, where):
    keys = strings(item.get('notes', []), f'Notes in {where}')
    require(len(keys) == len(set(keys)), f'Repeated note in {where}')
    require(all(k in notes for k in keys), f'Unknown note in {where}: {set(keys) - notes.keys()}')
    return keys


def load_records(root, categories, legacy, rulings):
    folder = root / 'data/concepts'
    records = {}
    for path in sorted(folder.glob('*.json')) if folder.exists() else []:
        record = json.loads(path.read_text(encoding='utf-8'))
        fields(record, ('id', 'english', 'domain', 'terms', 'sources', 'review'),
               ('sense', 'pos', 'also', 'also_under', 'wikidata', 'audience', 'phrases', 'notes', 'related', 'replaces'))
        key = string(record['id'])
        where = f'concept {key}'
        require(re.fullmatch(SLUG, key) and path.stem == key, f'Concept ID must be a slug matching its file name: {path.name}')
        string(record['english'])
        if 'pos' in record:
            pos = [record['pos']] if isinstance(record['pos'], str) else record['pos']
            require(isinstance(pos, list) and pos and len(pos) == len(set(pos)) and all(p in POS for p in pos),
                    f'Invalid part of speech in {where}: {record["pos"]}')
        if 'sense' in record:
            string(record['sense'])
        strings(record.get('also', []), f'Also in {where}')
        require(record['domain'] in categories, f'Unknown domain in {where}')
        under = strings(record.get('also_under', []), f'Also under in {where}')
        require(all(c in categories and c != record['domain'] for c in under) and len(under) == len(set(under)),
                f'Invalid also_under in {where}: {under}')
        require(re.fullmatch(r'Q[1-9][0-9]*', record.get('wikidata', 'Q1')), f'Invalid Wikidata item in {where}')
        require(record.get('audience', 'child') in ('child', 'adult'), f'Invalid audience in {where}')
        notes = record.get('notes', {})
        require(isinstance(notes, dict), f'Notes in {where} must be an object')
        for name, note in notes.items():
            require(re.fullmatch(SLUG, name), f'Invalid note key in {where}: {name}')
            fields(note, ('html',), ('ruling', 'form', 'claim', 'against'))
            rich(note['html'])
            require(('form' in note) == ('claim' in note), f'Note {name} in {where} needs both form and claim')
            require('against' not in note or 'form' in note, f'Note {name} in {where} has against without a form')
            for part in ('form', 'claim', 'against'):
                if part in note:
                    rich(note[part])
            if 'ruling' in note:
                require(note['ruling'] in rulings, f'Unknown ruling in {where}: {note["ruling"]}')
        used = []
        require(isinstance(record['terms'], list) and record['terms'], f'No terms in {where}')
        require(any(t.get('status') == 'recommended' for t in record['terms']), f'No recommended term in {where}')
        for term in record['terms']:
            fields(term, ('latin', 'status', 'period'), ('gloss', 'grammar', 'register', 'evidence', 'comment', 'notes'))
            string(term['latin'])
            require(term['status'] in STATUS_ORDER, f'Invalid status in {where}')
            require(term['period'] in PERIODS, f'Invalid period in {where}')
            for name in ('gloss', 'grammar'):
                if name in term:
                    string(term[name])
                    # Plain text: markup here is printed as written (it showed on the site, 11 Nov 2026).
                    require(not re.search(r'<|&(amp|quot|lt|gt);', term[name]), f'Markup in the {name} of {where}: plain text only')
            for name in ('register', 'comment'):
                if name in term:
                    rich(term[name])
            for evidence in strings(term.get('evidence', []), f'Evidence in {where}'):
                rich(evidence)
            used += check_notes(term, notes, where)
        # Coinages only where needed (Jack, 13 November 2026): a word or phrase of our own is in the
        # lexicon only when no author of any period has one for the concept, so it is never the
        # answer beside an attested word that is.
        ours = [t['latin'] for t in record['terms'] if t['status'] == 'recommended' and t['period'] == 'ours']
        attested = [t['latin'] for t in record['terms'] if t['status'] == 'recommended' and t['period'] != 'ours']
        require(not (ours and attested),
                f'{where} recommends our own “{ours[0] if ours else ""}” beside the attested “{attested[0] if attested else ""}”: '
                'a coinage is recommended only where no attested word is. Delete it, move it to the examples, '
                'or make one of the two an alternative')
        require(isinstance(record.get('phrases', []), list), f'Phrases in {where} must be a list')
        for phrase in record.get('phrases', []):
            fields(phrase, ('latin', 'english', 'source'), ('notes',))
            string(phrase['latin']), string(phrase['english']), rich(phrase['source'])
            require(not re.search(r'<|&(amp|quot|lt|gt);', phrase['latin'] + phrase['english']), f'Markup in an example of {where}: plain text only')
            used += check_notes(phrase, notes, where)
        require(set(notes) <= set(used), f'Unused notes in {where}: {set(notes) - set(used)}')
        strings(record.get('related', []), f'Related in {where}')
        for source in strings(record['sources'], f'Sources in {where}'):
            rich(source)
            # A source line is a citation, as a book would print it: the author, the work, the place
            # (Jack, 13 November 2026). How the book was read or checked is not part of it.
            require(not SOURCE_METHOD.search(source), f'A source in {where} describes how it was read; give only the citation: {source}')
        require(len(record['sources']) == len(set(record['sources'])), f'The same source twice in {where}')
        require(sum(TRAUPMAN in source for source in record['sources']) <= 1,
                f'Traupman is cited more than once in {where}; give one citation with all its pages')
        require(record['sources'], f'No sources in {where}')
        fields(record['review'], ('status', 'date', 'by'))
        require(record['review']['status'] in ('draft', 'reviewed'), f'Invalid review status in {where}')
        require(re.fullmatch(DATE, string(record['review']['date'])), f'Invalid review date in {where}')
        string(record['review']['by'])
        for old in strings(record.get('replaces', []), f'Replaces in {where}'):
            require(re.fullmatch(r'[a-z][a-z0-9-]*', old), f'Invalid replaced ID in {where}: {old}')
            require(old not in legacy and old not in {entry_html_id(e) for e in legacy.values()},
                    f'{where} replaces {old}, which still exists')
        records[key] = record
    headwords = {}
    for record in records.values():
        key = (record['english'].strip().lower(), record.get('sense', '').strip().lower())
        require(key not in headwords, f'Two records for “{record["english"]}”'
                + (f' ({record["sense"]})' if 'sense' in record else '')
                + f': {headwords.get(key)} and {record["id"]}; merge them, or give each its own sense')
        headwords[key] = record['id']
    replaced = [old for r in records.values() for old in r.get('replaces', [])]
    require(len(replaced) == len(set(replaced)), 'An old entry is replaced by two concepts')
    for record in records.values():
        for target in record.get('related', []):
            require(target in records or target in legacy, f'Unknown related target in concept {record["id"]}: {target}')
            require(target != record['id'], f'Concept {record["id"]} relates to itself')
    return records


def note_html(note):
    """A note as printed. A note on a form opens in one fixed shape, the form, what we write and the
    authority we depart from: "fortasse: short final e (Lewis & Short fortassē)", then its evidence."""
    if 'form' not in note:
        return note['html']
    against = f' ({note["against"]})' if 'against' in note else ''
    return f'<b class="nf" lang="la">{note["form"]}</b>: {note["claim"]}{against}. {note["html"]}'


def ordered_terms(record):
    return sorted(record['terms'], key=lambda t: STATUS_ORDER[t['status']])


def note_numbers(record):
    numbers = {}
    for item in ordered_terms(record) + record.get('phrases', []):
        for key in item.get('notes', []):
            numbers.setdefault(key, len(numbers) + 1)
    return numbers


def record_tags(record):
    tags = {PERIOD_TAGS[t['period']] for t in record['terms']}
    phrases = record.get('phrases', [])
    if any(not composed(p) for p in phrases) or any('lang="la"' in e for t in record['terms'] for e in t.get('evidence', [])):
        tags.add('Quotations')
    if any(composed(p) for p in phrases):
        tags.add('Composed phrases')
    if record['review']['status'] == 'draft':
        tags.add('Draft')
    return [t for t in TAG_ORDER if t in tags]


def record_heading(record):
    return ' · '.join(t['latin'] for t in record['terms'] if t['status'] == 'recommended')


def record_english(record):
    return record['english'] + (f' · {record["sense"]}' if 'sense' in record else '')


def pos_label(record):
    pos = record.get('pos')
    return ' and '.join([pos] if isinstance(pos, str) else pos) if pos else ''


def grammar(term):
    """The term's grammar in words, from its own field or from its dictionary form."""
    if 'grammar' in term:
        return term['grammar']
    match = NOUN_FORM.match(term['latin'])
    if match:
        genitive = match['gen'].lstrip('-')
        name = next((n for ending, n in DECLENSIONS if genitive.endswith(ending)), None)
        if name == 'fifth' and not match['head'].endswith('ēs'):
            name = 'second'   # malleus, malleī; hypogēum, hypogēī
        return (f'noun, {name} declension' if name else 'noun') + (', plural' if match['pl'] else '')
    match = VERB_FORM.match(term['latin'])
    if match and match['inf'].endswith(('re', 'rī', 'ī', 'sse')):   # not "major, majus" or "jūnior, jūniōris"
        name = next((n for ending, n in CONJUGATIONS if match['inf'].endswith(ending)), None)
        return f'verb, {name}' if name else 'verb'
    return ''


def term_head(latin):
    """The dictionary headword of a term: "caccabus" in "caccabus (cacabus), caccabī m."."""
    return TERM_HEAD.match(latin).group(1)


def wiktionary_title(head):
    """The page of English Wiktionary where a Latin word's forms are set out: the word without
    its macrons and with i for consonantal j, as Wiktionary writes its Latin headwords (jam is at
    "iam", Jēsus at "Iesus"); v and the capital of a name are kept."""
    text = unicodedata.normalize('NFD', head.replace('æ', 'ae').replace('œ', 'oe'))
    text = ''.join(c for c in text if not unicodedata.combining(c)).replace('j', 'i').replace('J', 'I')
    bare = text.rstrip('.!?')
    return bare.lower() if bare != text else text   # a one-word saying: "Ecce!" is at "ecce"


def wiktionary_url(head):
    return f'https://en.wiktionary.org/wiki/{quote(wiktionary_title(head))}#Latin'


# What a term's dictionary form shows of how it inflects, more loosely than the grammar line reads
# it: "auctor, auctōris m./f.", "mōtus, mōtūs m. (animī)", "vehor, vehī, vectus sum"; and an
# adjective's or a pronoun's forms: "bonus, bona, bonum", "ille, illa, illud", "ācer, ācris, ācre",
# "fidēlis, fidēle", "major, majus", "plūrēs, plūra", and the one-ending kind, "pār, paris".
_W = r'[^\s,()]+'
DECLINED = re.compile(rf'^{_W}(?: \([^)]*\))?, {_W} [mfnc](?:/[mfn])?\.'
                      rf'|^{_W}, {_W}(?:a|ae|aec), [^\s,()]*(?:um|ud|od|id|oc|em|a|ō)$|^{_W}(?:er|is), {_W}is, {_W}e$'
                      rf'|^{_W}(?:is|er), {_W}e$|^{_W}or, {_W}us$'
                      rf'|^{_W}ēs, {_W}a$|^{_W}(?:[ārx]|ns|ēs), {_W}is$')
CONJUGATED = re.compile(rf'^{_W}(?:ō|or|um)(?: \([^)]*\))?, {_W}(?:re|rī|ī|sse|lle)(?:,|$)')
INFLECTED = {'noun': 'Declension', 'adjective': 'Declension', 'pronoun': 'Declension', 'numeral': 'Declension',
             'verb': 'Conjugation'}


def inflection(term):
    """"Declension" or "Conjugation" where the term is a word given in its dictionary form, or a
    bare word whose grammar names its kind ("verb, third conjugation"); nothing for an adverb or
    a particle, a form of another word (animī, fīat) or a saying."""
    latin = re.sub(r' \(\+[^)]*\)$', '', term['latin'])   # "manifestus, manifesta, manifestum (+ gen.)"
    if CONJUGATED.match(latin):
        return 'Conjugation'
    if DECLINED.match(latin):
        return 'Declension'
    kind = re.match(r'(noun|adjective|pronoun|numeral|verb)(?=,|$)', term.get('grammar', ''))
    if kind and re.fullmatch(rf'{_W}(?: \([^)]*\))?', latin) and latin[-1] not in '.!?’' and ' of ' not in term['grammar']:
        return INFLECTED[kind[1]]
    return ''


def grammar_html(term):
    """The term's grammar, with the words that name its declension or conjugation linked to the word
    on Wiktionary (Jack, 13 November 2026): the lexicon prints no paradigms, and the link belongs on
    the word it explains, not in a label of its own. Where the grammar does not name the declension
    or conjugation ("verb", or none given), the bare word is added and linked. A term of several
    words, an adverb, a particle or a form of another word has no such link; its word page lists
    Wiktionary among the dictionaries."""
    text, label, head = escape(grammar(term)), inflection(term).lower(), term_head(term['latin'])
    if not label or ' ' in head or '’' in head:
        return text
    ordinal = '(?:first|second|third|fourth|fifth|mixed)'
    match = re.search(rf'(?:{ordinal}(?: and {ordinal})? )?{label}', text)
    link = (f'<a class="wikt" href="{wiktionary_url(head)}" title="{label.capitalize()} of {escape(head, quote=True)} on Wiktionary" '
            'rel="noopener noreferrer" target="_blank">')
    if match:
        return text[:match.start()] + link + match[0] + '</a>' + text[match.end():]
    return text + (', ' if text else '') + link + label + '</a>'


def load_latinitium(root):
    """Lewis & Short's entry numbers, by headword as Wiktionary would spell it (no macrons, i for
    j). Latinitium's dictionaries address an article by number alone, and its Lewis & Short keeps
    the numbers of the Perseus edition (Jack tried soror, videō and trulla, 13 November 2026):
    ?t=lsn44798 is soror. Several numbers, for homographs, are joined with commas."""
    path, table = root / 'refs/lewis-short-ids.tsv', {}
    if path.exists():
        for line in path.read_text(encoding='utf-8').splitlines():
            if line and not line.startswith('#'):
                key, ids = line.split('\t')
                table.setdefault(key.replace('j', 'i').replace('J', 'I'), []).extend(ids.split())
    return table


def latinitium_url(head, table):
    """The word's article in Lewis & Short on Latinitium, or nothing if Lewis & Short lacks it."""
    title = wiktionary_title(head)
    ids = table.get(title) or table.get(title.lower()) or table.get(title.capitalize())
    return 'https://latinitium.com/latin-dictionaries/?t=' + ','.join(f'lsn{n}' for n in ids) if ids else ''


