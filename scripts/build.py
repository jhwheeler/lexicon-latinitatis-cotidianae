class Document(HTMLParser):
    """Collect element IDs and local links of one generated page."""
    def __init__(self):
        super().__init__()
        self.ids = set()
        self.links = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if 'id' in attrs:
            require(attrs['id'] not in self.ids, f'Duplicate HTML ID: {attrs["id"]}')
            self.ids.add(attrs['id'])
        href = attrs.get('href') or ''
        if href and not href.startswith(('https://', 'http://', 'mailto:')):
            self.links.append(href)


def check_links(outputs):
    """Every local link must reach a generated page and, with a fragment, an ID on it."""
    documents = {}
    for path, text in outputs.items():
        if path.endswith('.html'):
            doc = Document()
            doc.feed(text)
            documents[path] = doc
    broken = []
    for path, doc in documents.items():
        for link in doc.links:
            target, _, fragment = link.partition('#')
            target = posixpath.normpath(posixpath.join(posixpath.dirname(path), target)) if target else path
            if target not in outputs or (fragment and (target not in documents or fragment not in documents[target].ids)):
                broken.append(f'{path} → {link}')
    require(not broken, f'Broken fragment links: {broken[:8]}')


def load_site(root):
    catalog = json.loads((root / 'data/catalog.json').read_text(encoding='utf-8'))
    fields(catalog, ('version', 'categories', 'filters'))
    require(catalog['version'] == 1, 'Unsupported catalog version')
    require(isinstance(catalog['categories'], list) and catalog['categories'], 'No categories')
    categories, legacy, anchors = {}, {}, set()
    entries = {}
    for category in catalog['categories']:
        fields(category, ('id', 'english', 'latin'), ('aliases',))
        key = string(category['id'])
        require(re.fullmatch(r'[a-z][a-z0-9-]*', key), 'Invalid category ID')
        for alias in strings(category.get('aliases', []), f'Aliases of category {key}'):
            require(re.fullmatch(r'[a-z][a-z0-9-]*', alias), f'Invalid alias of category {key}: {alias}')
        require(key not in categories and key != 'all', f'Duplicate/reserved category: {key}')
        categories[key] = category
        items = json.loads((root / f'data/entries/{key}.json').read_text(encoding='utf-8'))
        require(isinstance(items, list), f'Entries of {key} must be a list')
        for entry in items:
            require(isinstance(entry, dict) and entry.get('id') not in legacy, f'Duplicate entry: {entry.get("id")}')
            if entry.get('anchor'):
                require(entry['anchor'] not in anchors, 'Duplicate entry anchor')
                anchors.add(entry['anchor'])
            legacy[entry['id']] = entry
        entries[key] = items
    files = {p.stem for p in (root / 'data/entries').glob('*.json')}
    require(files == set(categories), f'Unlisted or missing category files: {files ^ set(categories)}')
    rulings = load_rulings(root)
    site = {'catalog': catalog, 'categories': categories, 'entries': entries, 'legacy': legacy, 'rulings': rulings}
    site['records'] = load_records(root, categories, legacy, rulings)
    site['words'] = word_index(site['records'])
    site['anchors'] = anchor_map(site)
    for key in categories:
        require(entries[key] or any(key in [r['domain']] + r.get('also_under', []) for r in site['records'].values()),
                f'Empty category: {key}')
    return site


def anchor_map(site):
    """Where the anchors of the old single-page index lead now, as paths from the site's root:
    categories to their pages, records (and the cards they replaced) to theirs, cards not yet
    converted to their place on their category's page."""
    target = {}
    for key, category in site['categories'].items():
        target[key] = f'k/{key}.html'
        for alias in category.get('aliases', []):
            target[alias] = f'k/{key}.html'
        for entry in site['entries'][key]:
            target[entry['id']] = target[entry_html_id(entry)] = f'k/{key}.html#{entry_html_id(entry)}'
    for key, record in site['records'].items():
        target[f'c-{key}'] = f'c/{key}.html'
        for old in record.get('replaces', []):
            target[old] = f'c/{key}.html'
        for n in note_numbers(record).values():
            target[f'fn-{key}-{n}'] = f'c/{key}.html#fn-{key}-{n}'
    return target


def resolve_anchors(html, site, up, page):
    """Point links to anchors of the old index (href="#…", as card text has them) at the page that
    now holds the target; a link to this page's own anchors stays as it is."""
    targets = site['anchors']

    def resolve(match):
        key = match.group(1)
        if key not in targets:
            return match.group(0)
        path, _, fragment = targets[key].partition('#')
        if path == page:
            return f'href="#{fragment or key}"'
        return f'href="{up}{targets[key]}"'
    return re.sub(r'href="#([^"]+)"', resolve, html)


