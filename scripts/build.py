def grammar(term):
    """The term's grammar in words, from its own field or from its dictionary form."""
    if 'grammar' in term:
        return term['grammar']
    match = NOUN_FORM.match(term['latin'])
    if match:
        genitive = match['gen'].lstrip('-')
        name = next((n for ending, n in DECLENSIONS if genitive.endswith(ending)), None)
        if name == 'fifth' and not match['head'].endswith('ēs'):
            name = 'second'   # malleus, malleī; hypogēum, hypogēī
        return (f'noun, {name} declension' if name else 'noun') + (', plural' if match['pl'] else '')
    match = VERB_FORM.match(term['latin'])
    if match and match['inf'].endswith(('re', 'rī', 'ī', 'sse')):   # not "major, majus" or "jūnior, jūniōris"
        name = next((n for ending, n in CONJUGATIONS if match['inf'].endswith(ending)), None)
        return f'verb, {name}' if name else 'verb'
    return ''


def term_head(latin):
    """The dictionary headword of a term: "caccabus" in "caccabus (cacabus), caccabī m.". A saying
    is its own head, commas and all: the comma in "Eho, nōn tam cito!" divides a sentence, not a
    headword from its forms, and cut there the saying became a page for the word eho that defined
    it as "whoa, not so fast!" (Jack, 18 November 2026). Nor is it cut at a bracket inside it
    ("Nōlī (nōlīte) exscrībere ex proximō." is not the word nōlī), only at one that ends it
    ("Grātulor (tibi)!")."""
    if is_saying(latin):
        return SAYING_HEAD.match(latin).group(1)
    return TERM_HEAD.match(latin).group(1)


def wiktionary_title(head):
    """The page of English Wiktionary where a Latin word's forms are set out: the word without
    its macrons and with i for consonantal j, as Wiktionary writes its Latin headwords (jam is at
    "iam", Jēsus at "Iesus"); v and the capital of a name are kept."""
    text = unicodedata.normalize('NFD', head.replace('æ', 'ae').replace('œ', 'oe'))
    text = ''.join(c for c in text if not unicodedata.combining(c)).replace('j', 'i').replace('J', 'I')
    bare = text.rstrip('.!?')
    return bare.lower() if bare != text else text   # a one-word saying: "Ecce!" is at "ecce"


def wiktionary_url(head):
    return f'https://en.wiktionary.org/wiki/{quote(wiktionary_title(head))}#Latin'


# What a term's dictionary form shows of how it inflects, more loosely than the grammar line reads
# it: "auctor, auctōris m./f.", "mōtus, mōtūs m. (animī)", "vehor, vehī, vectus sum"; and an
# adjective's or a pronoun's forms: "bonus, bona, bonum", "ille, illa, illud", "ācer, ācris, ācre",
# "fidēlis, fidēle", "major, majus", "plūrēs, plūra", and the one-ending kind, "pār, paris".
_W = r'[^\s,()]+'
DECLINED = re.compile(rf'^{_W}(?: \([^)]*\))?, {_W} [mfnc](?:/[mfn])?\.'
                      rf'|^{_W}, {_W}(?:a|ae|aec), [^\s,()]*(?:um|ud|od|id|oc|em|a|ō)$|^{_W}(?:er|is), {_W}is, {_W}e$'
                      rf'|^{_W}(?:is|er), {_W}e$|^{_W}or, {_W}us$'
                      rf'|^{_W}ēs, {_W}a$|^{_W}(?:[ārx]|ns|ēs), {_W}is$')
CONJUGATED = re.compile(rf'^{_W}(?:ō|or|um)(?: \([^)]*\))?, {_W}(?:re|rī|ī|sse|lle)(?:,|$)')
INFLECTED = {'noun': 'Declension', 'adjective': 'Declension', 'pronoun': 'Declension', 'numeral': 'Declension',
             'verb': 'Conjugation'}


def inflection(term):
    """"Declension" or "Conjugation" where the term is a word given in its dictionary form, or a
    bare word whose grammar names its kind ("verb, third conjugation"); nothing for an adverb or
    a particle, a form of another word (animī, fīat) or a saying."""
    latin = re.sub(r' \(\+[^)]*\)$', '', term['latin'])   # "manifestus, manifesta, manifestum (+ gen.)"
    if CONJUGATED.match(latin):
        return 'Conjugation'
    if DECLINED.match(latin):
        return 'Declension'
    kind = re.match(r'(noun|adjective|pronoun|numeral|verb)(?=,|$)', term.get('grammar', ''))
    if kind and re.fullmatch(rf'{_W}(?: \([^)]*\))?', latin) and latin[-1] not in '.!?’' and ' of ' not in term['grammar']:
        return INFLECTED[kind[1]]
    return ''


def grammar_html(term):
    """The term's grammar, with the words that name its declension or conjugation linked to the word
    on Wiktionary (Jack, 13 November 2026): the lexicon prints no paradigms, and the link belongs on
    the word it explains, not in a label of its own. Where the grammar does not name the declension
    or conjugation ("verb", or none given), the bare word is added and linked. A term of several
    words, an adverb, a particle or a form of another word has no such link; its word page lists
    Wiktionary among the dictionaries."""
    text, label, head = escape(grammar(term)), inflection(term).lower(), term_head(term['latin'])
    if not label or ' ' in head or '’' in head:
        return text
    ordinal = '(?:first|second|third|fourth|fifth|mixed)'
    match = re.search(rf'(?:{ordinal}(?: and {ordinal})? )?{label}', text)
    link = (f'<a class="wikt" href="{wiktionary_url(head)}" title="{label.capitalize()} of {escape(head, quote=True)} on Wiktionary" '
            'rel="noopener noreferrer" target="_blank">')
    if match:
        return text[:match.start()] + link + match[0] + '</a>' + text[match.end():]
    return text + (', ' if text else '') + link + label + '</a>'


def load_latinitium(root):
    """Lewis & Short's entry numbers, by headword as Wiktionary would spell it (no macrons, i for
    j). Latinitium's dictionaries address an article by number alone, and its Lewis & Short keeps
    the numbers of the Perseus edition (Jack tried soror, videō and trulla, 13 November 2026):
    ?t=lsn44798 is soror. Several numbers, for homographs, are joined with commas."""
    path, table = root / 'refs/lewis-short-ids.tsv', {}
    if path.exists():
        for line in path.read_text(encoding='utf-8').splitlines():
            if line and not line.startswith('#'):
                key, ids = line.split('\t')
                table.setdefault(key.replace('j', 'i').replace('J', 'I'), []).extend(ids.split())
    return table


def latinitium_url(head, table):
    """The word's article in Lewis & Short on Latinitium, or nothing if Lewis & Short lacks it."""
    title = wiktionary_title(head)
    ids = table.get(title) or table.get(title.lower()) or table.get(title.capitalize())
    return 'https://latinitium.com/latin-dictionaries/?t=' + ','.join(f'lsn{n}' for n in ids) if ids else ''


