def render_az_pages(site):
    """The English and the Latin words from A to Z."""
    # A record listed under several categories appears once, under its own.
    rows = sorted({row[4]: row for key in site['categories'] for row in category_entries(key, site)}.values(),
                  key=lambda row: (row[0], row[4]))
    names = {f'k/{key}.html': c['latin'] for key, c in site['categories'].items()}

    def category_of(path):
        if path.startswith('k/'):
            return names[path.split('#')[0]]
        return site['categories'][site['records'][path[2:-5]]['domain']]['latin']

    def letters(items, letter_of, render):
        groups = {}
        for item in items:
            groups.setdefault(letter_of(item), []).append(item)
        nav = ''.join(f'<a href="#letter-{c}">{c.upper()}</a>' for c in groups)
        return (f'<nav class="az-nav" aria-label="Letters">{nav}</nav>'
                + ''.join(f'<section class="az-letter" id="letter-{c}"><h2>{c.upper()}</h2>{render(group)}</section>'
                          for c, group in groups.items()))
    # The order is by letters alone: -ne, -que and -ve stand among the words in n, q and v, where a
    # reader looks for them, not ahead of a (they used to put N, Q and V first; Jack, 13 November 2026).
    letters_of = lambda text: re.sub(r'[^a-z]', '', text) or '#'
    first = lambda text: letters_of(text)[0]
    rows = sorted(rows, key=lambda row: (letters_of(row[0]), row[0], row[4]))
    english = letters(rows, lambda row: first(row[0]), lambda group: word_list(group, '', category_of).replace('class="wlist"', 'class="wlist az-list"', 1))
    words = sorted(site['words'].items(), key=lambda item: (letters_of(fold(item[0])), fold(item[0]), item[1]['slug']))

    # The Latin index lists the words, each with its page, and the phrases too (Jack, 13 November
    # 2026): the Latin of every record that is a phrase, whole, leading to its entry, so that the
    # sayings can be found from their Latin and browsed with the same filter as the English index.
    latin_rows = []
    for head, info in words:
        # Each meaning once, though several records gloss the word alike.
        meanings = ', '.join(dict.fromkeys(part.strip() for r, t in info['uses']
                                           for part in re.split(r'[,;] ', t.get('gloss', r['english'])) if part.strip()))
        latin_rows.append((letters_of(fold(head)), fold(head), head, meanings, f'l/{info["slug"]}.html', 'word'))
    phrases = 0
    for record in site['records'].values():
        if not is_phrase(record):
            continue
        for term in ordered_terms(record):
            if term['status'] == 'avoid' or ' ' not in term['latin']:
                continue   # a phrase of one word (Salvē!) is in the list already, as a word
            phrases += 1
            latin_rows.append((letters_of(fold(term['latin'])), fold(term['latin']), term['latin'],
                               term.get('gloss', record['english']), f'c/{record["id"]}.html', 'phrase'))
    latin_rows.sort()

    def latin_list(group):
        return '<ul class="wlist az-list latin">' + ''.join(
            f'<li data-kind="{kind}"><a href="{href}"><span class="w-la" lang="la">{escape(text)}</span>'
            f'<span class="w-en">{escape(english)}</span></a></li>' for _, _, text, english, href, kind in group) + '</ul>'
    latin = letters(latin_rows, lambda row: row[0][0], latin_list)
    pages = {}
    pages['words.html'] = page_shell(f'English words A–Z · {SITE_NAME}',
                                     'Every English headword of the lexicon, from A to Z, with its Latin.', 'words.html', '',
                                     f'<h1 class="page-title">English words, A–Z</h1><p class="lead">{len(rows)} entries. '
                                     'For the Latin words, see <a href="latin.html">the Latin index</a>.</p>' + KIND_FILTER + english)
    pages['latin.html'] = page_shell(f'Latin words A–Z · {SITE_NAME}',
                                     'Every Latin word that heads an entry of the lexicon, from A to Z, with its meanings.', 'latin.html', '',
                                     f'<h1 class="page-title">Latin words, A–Z</h1><p class="lead">{len(words):,} words, each with a page '
                                     f'that gathers its entries, and {phrases:,} phrases. For the English words, see '
                                     '<a href="words.html">the English index</a>.</p>' + KIND_FILTER + latin)
    return pages


def line_kind(html):
    """A grouped card's line, as the search ranks it: a definition starts with a Latin headword,
    an example with a Latin sentence."""
    m = re.match(r'\s*<strong lang="la">(.*?)</strong>', html)
    if not m:
        return 'e', '', plain(html)
    latin = plain(m.group(1))
    definition = len(latin.split()) <= 10 and (re.match(r'[a-zāēīōūȳæœ]', latin) or re.search(r'\b[mfn]\.\s*(pl\.)?$', latin))
    return ('d' if definition else 'e'), latin, plain(html[m.end():]).lstrip('—–- ').strip()


def search_data(site):
    """The search index, as a script (so that search also works on pages opened from disk)."""
    items = []
    for key in site['catalog']['filters']:
        if key == 'all':
            continue
        for _, english, pos, latin, path, item in category_entries(key, site):
            if path.startswith('c/'):
                record = item
                if record['domain'] != key:
                    continue   # listed here too, but indexed once, under its own category
                lines = [['d', t['latin'], t.get('gloss', ''), plain(term_meta(t))] for t in ordered_terms(record)]
                lines += [['e', p['latin'], p['english'], 'composed' if composed(p) else plain(p['source'])] for p in record.get('phrases', [])]
                lines += [['n', plain(note_html(record['notes'][n]))] for n in note_numbers(record)]
                # Each term's head and the stems its forms are built on: [head, class, stem, class, stem…]
                # The search folds v as u, as it folds j as i (videō, uideō), so the stems are sent folded.
                forms = [[term_head(t['latin'])] + [part for cls, stem in stems for part in (cls, uv_fold(stem))]
                         for t in ordered_terms(record) if (stems := search_stems(t))]
                items.append({'id': f'c-{record["id"]}', 'u': path, 'k': key, 'en': english, 'pos': pos,
                              'al': '; '.join(record.get('also', [])), 'l': lines,
                              **({'x': record['also_under']} if record.get('also_under') else {}),
                              **({'f': forms} if forms else {})})
            else:
                entry, lines = item, []
                for block in entry['blocks']:
                    for li in block.get('items', []):
                        lines.append(list(line_kind(li['html'])))
                    if block['type'] == 'paragraph':
                        lines.append(['n', plain(block['html'])])
                    for paragraph in block.get('paragraphs', []):
                        lines.append(['n', plain(paragraph)])
                items.append({'id': entry['id'], 'u': path, 'k': key, 'en': english, 'la': latin,
                              'al': entry.get('keywords', ''), 'l': lines})
    data = {'categories': {key: c['latin'] for key, c in site['categories'].items()}, 'endings': {cls: [uv_fold(e) for e in endings] for cls, endings in ENDINGS.items()}, 'items': items}
    return 'window.lexiconData = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n'


# Review (Jack, 15 November 2026) ----------------------------------------------------------------
# Every record is a draft until the editor says it is right. He does not give that verdict on the
# site: he reviews in a private page of his own, built by scripts/editor_review.py, and the site
# never prints his name. What the site offers is the flag: a reader flags an entry on its page or on
# the back of a practice card; the flags are kept on the device and gathered into one report on
# review.html. The editor's report and a reader's have one format, and scripts/apply_review.py
# applies either to the records. See docs/review.md.
def record_revision(record):
    """A short name for the text of a record as it stands: a hash of its JSON without the `review`
    field. A verdict is tied to it, so that "looks right" given on one text is not applied to
    another, and marking a record reviewed does not change it. The page (data-rev), the practice
    cards and scripts/apply_review.py all use this one function."""
    text = json.dumps({key: value for key, value in record.items() if key != 'review'},
                      ensure_ascii=False, sort_keys=True, separators=(',', ':'))
    return hashlib.sha256(text.encode('utf-8')).hexdigest()[:8]


def reviewed(record):
    return record['review']['status'] == 'reviewed'


def concept_article(record):
    """The opening tag of an entry's article, with what the review needs: the record's revision
    and whether the editor has reviewed it."""
    return (f'<article class="concept" data-record data-rev="{record_revision(record)}" '
            f'data-status="{record["review"]["status"]}">')


def render_review_page(root, site):
    """review.html: how many entries are reviewed, and the reader's flags gathered into a report to
    send. With scripts it is drawn by assets/review.js from the practice cards, which carry each
    record's revision and whether it is reviewed; without them the line of totals stands."""
    total = len(site['records'])
    done = sum(reviewed(record) for record in site['records'].values())
    return fill(root / 'src/review.html', {
        'theme': THEME_INIT, 'app': app_head(''), 'header': site_header(''), 'footer': site_footer(''),
        'reviewed': f'{done:,}', 'drafts': f'{total - done:,}'})


# Practice (Jack, 13 November 2026) ---------------------------------------------------------------
# practice.html drills the lexicon's own records: an English cue, the Latin to say aloud, and
# spaced repetition whose progress stays on the reader's device. Its cards are a script of their
# own (assets/practice-data.js), one card per record, so that the page also works from disk.
# Vocabulary is the primary thing and phrases are secondary, so every card has a kind, and the
# phrases are split in two: the everyday phrases of conversation (how are you, thank you, in
# short) and the sayings and quotations (proverbs, maxims, lines of the authors).
#
# A phrase is a saying when its main term (1) stands in Traupman's list of proverbs and sayings
# (his Appendix IV, pp. 254–259), or (2) is a line of Publilius Syrus, or (3) is cited only from
# authors, with no page of Traupman or another handbook, and is a whole statement, not a turn of
# conversation: the Latin is a sentence of three words or more that ends in a full stop or a
# question mark, and the English headword has three words or more and no "I", "me" or "you", no
# contraction and no exclamation mark (so "it's too early" and "see you soon", both quoted from
# comedy and from letters, stay everyday phrases). Every other phrase is an everyday phrase.
PROVERB_PAGES = range(254, 260)
HANDBOOK = re.compile(r'Traupman|M-O|Morgan–Owens|Lewis (?:&|and) Short|L&S|Andresian|Levi–Bini|Graesse|Vatican|LRL|cf\.')


def practice_kind(record):
    """'w' a word, 'p' an everyday phrase, 's' a saying or quotation."""
    if not is_phrase(record):
        return 'w'
    main = ordered_terms(record)[0]
    cited = [plain(evidence) for evidence in main.get('evidence', [])]
    pages = [int(n) for text in cited if text.startswith('Traupman') for n in re.findall(r'\d+', text.split(':')[0])]
    if any(page in PROVERB_PAGES for page in pages) or any(re.match(r'(?:Ps\.-)?Publ(?:il)?\.', text) for text in cited):
        return 's'
    latin, english = main['latin'], record['english']
    if cited and not any(HANDBOOK.match(text) for text in cited):
        statement = (re.match(r'[A-ZĀĒĪŌŪ]', latin) and latin[-1] in '.?' and '—' not in latin and len(latin.split()) >= 3)
        spoken = len(english.split()) < 3 or re.search(r"[’'!]|\b(?:I|me|you)\b", english)
        if statement and not spoken:
            return 's'
    return 'p'


