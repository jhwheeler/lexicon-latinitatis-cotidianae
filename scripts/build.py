def grammar(term):
    """The term's grammar in words, from its own field or from its dictionary form."""
    if 'grammar' in term:
        return term['grammar']
    match = NOUN_FORM.match(term['latin'])
    if match:
        genitive = match['gen'].lstrip('-')
        name = next((n for ending, n in DECLENSIONS if genitive.endswith(ending)), None)
        if name == 'fifth' and not match['head'].endswith('ēs'):
            name = 'second'   # malleus, malleī; hypogēum, hypogēī
        return (f'noun, {name} declension' if name else 'noun') + (', plural' if match['pl'] else '')
    match = VERB_FORM.match(term['latin'])
    if match:
        name = next((n for ending, n in CONJUGATIONS if match['inf'].endswith(ending)), None)
        return f'verb, {name}' if name else 'verb'
    return ''


def term_head(latin):
    """The dictionary headword of a term: "caccabus" in "caccabus (cacabus), caccabī m."."""
    return TERM_HEAD.match(latin).group(1)


def fold(text):
    """Lower case without macrons or other marks, as search compares words."""
    text = unicodedata.normalize('NFD', text.lower()).replace('æ', 'ae').replace('œ', 'oe')
    return ''.join(c for c in text if not unicodedata.combining(c))


# The search finds a Latin word from any of its forms (piscīnam finds piscīna, dīxit finds dīcō):
# each term gives the stems its forms are built on, each with a class of endings, and the search
# (src/search.js) takes an ending off what was typed and looks up what is left. Stems and endings
# are folded as the search folds what is typed: no macrons, and j as i.
def _persons(base, passive=False):
    return [base + e for e in (('r', 'ris', 're', 'tur', 'mur', 'mini', 'ntur') if passive
                               else ('m', 's', 't', 'mus', 'tis', 'nt'))]


def _tense(base):
    return _persons(base) + _persons(base, passive=True)


