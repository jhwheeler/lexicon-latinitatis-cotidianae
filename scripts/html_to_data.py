#!/usr/bin/env python3
"""Extract structured lexicon data from a lexicon page (stdlib only).

This is the reverse of scripts/build.py. It reads a lexicon page, either a
hand-edited one from before the structured migration or a generated one, and
writes data/catalog.json and data/entries/<category>.json in the format of
docs/data-format.md. With --template it also writes the page shell
(src/page.html, src/styles.css, src/search.js).

Use it to migrate content that was edited directly in index.html (an old
branch or pull request) into the data files, then rebuild and review the diff:

    python3 scripts/html_to_data.py old-index.html --out /tmp/converted
    diff -r data /tmp/converted/data

The converter refuses markup outside the schema (unknown block elements,
classes or stray text) rather than silently dropping it.
"""
import argparse
from html import escape
from html.parser import HTMLParser
import json
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
VOID = {'area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input', 'link', 'meta', 'source', 'track', 'wbr'}
GENERATED = '<!-- Generated by scripts/build.py. Edit data/ and src/, then rebuild. -->\n'


class Node:
    def __init__(self, tag, attrs, parent=None):
        self.tag, self.attrs, self.parent, self.children = tag, attrs, parent, []

    def attr(self, key, default=None):
        for k, v in self.attrs:
            if k == key:
                return v
        return default

    def has(self, key):
        return any(k == key for k, _ in self.attrs)

    def classes(self):
        return (self.attr('class') or '').split()

    def elements(self):
        return [c for c in self.children if isinstance(c, Node)]

    def walk(self):
        for child in self.elements():
            yield child
            yield from child.walk()

    def find_all(self, test):
        return [n for n in self.walk() if test(n)]

    def text(self):
        return ''.join(c if isinstance(c, str) else c.text() for c in self.children)


class Tree(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.root = Node('#root', [])
        self.current = self.root

    def handle_starttag(self, tag, attrs):
        node = Node(tag, attrs, self.current)
        self.current.children.append(node)
        if tag not in VOID:
            self.current = node

    def handle_startendtag(self, tag, attrs):
        self.current.children.append(Node(tag, attrs, self.current))

    def handle_endtag(self, tag):
        if tag in VOID:
            return
        node = self.current
        while node is not self.root and node.tag != tag:
            node = node.parent
        if node is self.root:
            raise ValueError(f'Unmatched closing tag </{tag}> near line {self.getpos()[0]}')
        if node is not self.current:
            raise ValueError(f'Unclosed <{self.current.tag}> before </{tag}> near line {self.getpos()[0]}')
        self.current = node.parent

    def handle_data(self, data):
        self.current.children.append(data)


def parse(page):
    tree = Tree()
    tree.feed(page)
    tree.close()
    return tree.root


def inner_html(node):
    """Serialize children the way the data files store rich text.

    Text is re-escaped (&, <, >); attributes are written in alphabetical order
    with double quotes. Whitespace inside the fragment is kept as it is.
    """
    out = []
    for child in node.children:
        if isinstance(child, str):
            out.append(escape(child, quote=False))
            continue
        attrs = ''.join(f' {k}' if v is None else f' {k}="{escape(v, quote=True)}"'
                        for k, v in sorted(child.attrs))
        out.append(f'<{child.tag}{attrs}>')
        if child.tag not in VOID:
            out.append(inner_html(child) + f'</{child.tag}>')
    return ''.join(out)


def fail(node, message):
    raise ValueError(f'{message} (in {node.tag} {dict(node.attrs)})')


def only_whitespace(node, context):
    for child in node.children:
        if isinstance(child, str) and child.strip():
            fail(node, f'Unexpected text in {context}: {child.strip()[:60]!r}')


def one(node, test, what):
    found = node.find_all(test)
    if len(found) != 1:
        fail(node, f'Expected one {what}, found {len(found)}')
    return found[0]


def convert_block(node):
    classes = node.classes()
    if node.tag == 'ul':
        if node.attrs:
            fail(node, 'Unsupported attributes on list')
        only_whitespace(node, 'list')
        items = []
        for li in node.elements():
            if li.tag != 'li':
                fail(li, 'Lists may contain only li')
            if [k for k, _ in li.attrs if k != 'class'] or li.classes() not in ([], ['note']):
                fail(li, 'Unsupported list-item attributes')
            item = {'html': inner_html(li)}
            if li.has('class'):
                item['class'] = 'note'
            items.append(item)
        return {'type': 'list', 'items': items}
    if node.tag == 'p':
        if [k for k, _ in node.attrs if k != 'class'] or classes not in ([], ['source-note']):
            fail(node, 'Unsupported paragraph attributes')
        block = {'type': 'paragraph', 'html': inner_html(node)}
        if node.has('class'):
            block['class'] = 'source-note'
        return block
    if node.tag == 'details' and classes == ['entry-sources'] and len(node.attrs) == 1:
        only_whitespace(node, 'sources')
        parts = node.elements()
        if not parts or parts[0].tag != 'summary' or any(p.tag != 'p' or p.attrs for p in parts[1:]):
            fail(node, 'Sources must be a summary followed by plain paragraphs')
        return {'type': 'sources', 'summary': parts[0].text(),
                'paragraphs': [inner_html(p) for p in parts[1:]]}
    fail(node, 'Unsupported entry-body element')


def convert_entry(article):
    known = {'class', 'id', 'data-entry', 'data-entry-id', 'data-category', 'data-search'}
    extra = {k for k, _ in article.attrs} - known
    if extra:
        fail(article, f'Unsupported article attributes {extra}')
    only_whitespace(article, 'entry')
    head = one(article, lambda n: n.tag == 'header' and 'entry-head' in n.classes(), 'entry header')
    english = one(head, lambda n: n.tag == 'p' and 'eyebrow' in n.classes(), 'English heading')
    latin = one(head, lambda n: n.tag == 'h3', 'Latin heading')
    tags = [t.text() for t in head.find_all(lambda n: n.tag == 'span' and 'tag' in n.classes())]
    body = one(article, lambda n: n.tag == 'div' and 'entry-body' in n.classes(), 'entry body')
    only_whitespace(body, 'entry body')
    entry = {'id': article.attr('data-entry-id')}
    if article.attr('id'):
        entry['anchor'] = article.attr('id')
    entry.update(english=english.text(), latin=latin.text(), tags=tags)
    if article.attr('data-search'):
        entry['keywords'] = article.attr('data-search')
    entry['blocks'] = [convert_block(b) for b in body.elements()]
    return entry


def convert(page):
    """Return (catalog, {category id: [entries]}) for a lexicon page."""
    root = parse(page)
    categories, entries = [], {}
    for section in root.find_all(lambda n: n.tag == 'section' and n.has('data-category-section')):
        key = section.attr('data-category-section')
        heading = one(section, lambda n: 'category-heading' in n.classes(), 'category heading')
        english = one(heading, lambda n: n.tag == 'p' and 'eyebrow' in n.classes(), 'category English heading')
        latin = one(heading, lambda n: n.tag == 'h2', 'category Latin heading')
        categories.append({'id': key, 'english': english.text(), 'latin': latin.text()})
        articles = section.find_all(lambda n: n.tag == 'article' and n.has('data-entry'))
        for article in articles:
            if article.attr('data-category') != key:
                fail(article, f'Entry is in section {key} but says data-category={article.attr("data-category")}')
        entries[key] = [convert_entry(a) for a in articles]
        count = heading.find_all(lambda n: 'category-count' in n.classes())
        if count and count[0].text().strip() != f'{len(articles)} entries':
            print(f'Note: {key} heading said {count[0].text().strip()!r}; it has {len(articles)} entries '
                  '(the builder regenerates counts)', file=sys.stderr)
    stray = [a for a in root.find_all(lambda n: n.tag == 'article' and n.has('data-entry'))
             if not any(p.tag == 'section' and p.has('data-category-section') for p in ancestors(a))]
    if stray:
        fail(stray[0], 'Entry outside any category section')
    filters = [b.attr('data-filter') for b in root.find_all(lambda n: n.has('data-filter'))]
    return {'version': 1, 'categories': categories, 'filters': filters}, entries


def ancestors(node):
    while node.parent is not None:
        node = node.parent
        yield node


def template(page):
    """Split a page into the src/ shell: (page.html, styles.css, search.js)."""
    def cut(pattern, token, text):
        match = re.search(pattern, text, flags=re.S)
        if not match:
            raise ValueError(f'Could not locate the {token} region of the page')
        return text[:match.start(1)] + token + text[match.end(1):], match.group(1)

    shell, styles = cut(r'<style>\n(.*?)</style>', '{{styles}}', page)
    shell, search = cut(r'<script>\n(.*?)</script>', '{{search}}', shell)
    shell, _ = cut(r'<div class="chips">(.*?)</div>', '{{filters}}', shell)
    shell, _ = cut(r'<p id="empty"[^>]*>.*?</p>\n(.*)\n</main>', '{{entries}}', shell)
    shell, _ = cut(r'<p class="eyebrow">[^<]*?· (\d+) grouped entries', '{{entry_count}}', shell)
    if not shell.startswith(GENERATED):
        shell = GENERATED + shell
    return shell, styles, search


def dump(value):
    return json.dumps(value, ensure_ascii=False, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('page', type=Path, help='lexicon page to read, e.g. an old index.html')
    parser.add_argument('--out', type=Path, default=ROOT,
                        help='repository root to write data/ (and src/) into; default: this repository')
    parser.add_argument('--template', action='store_true',
                        help='also write src/page.html, src/styles.css and src/search.js from the page')
    args = parser.parse_args()
    try:
        page = args.page.read_text(encoding='utf-8')
        catalog, entries = convert(page)
        shell = template(page) if args.template else None
    except (ValueError, OSError) as error:
        print(f'Conversion failed: {error}', file=sys.stderr)
        return 1
    data = args.out / 'data' / 'entries'
    data.mkdir(parents=True, exist_ok=True)
    stale = {p.stem for p in data.glob('*.json')} - entries.keys()
    for name in sorted(stale):
        (data / f'{name}.json').unlink()
    (args.out / 'data' / 'catalog.json').write_text(dump(catalog), encoding='utf-8')
    for key, items in entries.items():
        (data / f'{key}.json').write_text(dump(items), encoding='utf-8')
    if shell:
        src = args.out / 'src'
        src.mkdir(parents=True, exist_ok=True)
        for name, text in zip(('page.html', 'styles.css', 'search.js'), shell):
            (src / name).write_text(text, encoding='utf-8')
    total = sum(len(v) for v in entries.values())
    print(f'Wrote {total} entries in {len(entries)} categories to {args.out / "data"}'
          + (' and the page shell to src/' if shell else '') + '.')
    return 0


if __name__ == '__main__':
    sys.exit(main())
